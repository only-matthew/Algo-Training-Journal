export const TAG_COMPOUNDS = new Map(compounds);

function caseNormalizeLatin(tag) {
  return tag.replace(/[a-z]+/gi, (match) => {
    const upper = match.toUpperCase();
    if (CANONICAL_TAG_SET.has(upper) || TAG_ALIASES.has(match.toLowerCase())) {
      return upper;
    }
    return match;
  });
}

export function normalizeTag(tag) {
  const normalized = caseNormalizeLatin(tag);

  if (TAG_COMPOUNDS.has(normalized)) {
    const parts = TAG_COMPOUNDS.get(normalized).map((t) => normalizeTag(t));
    if (parts.length === 1) return parts[0];
    return parts;
  }

  const lower = normalized.toLowerCase();
  if (TAG_ALIASES.has(lower)) {
    return TAG_ALIASES.get(lower);
  }

  if (!/[\u4e00-\u9fff]/.test(normalized) && CANONICAL_TAG_SET.has(normalized.toUpperCase())) {
    return normalized.toUpperCase();
  }

  return normalized;
}

export function normalizeTagList(tags) {
  const result = [];
  for (const tag of tags) {
    const normalized = normalizeTag(tag);
    if (Array.isArray(normalized)) {
      result.push(...normalized);
    } else if (normalized) {
      result.push(normalized);
    }
  }
  return result;
}
